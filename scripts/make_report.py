"""Aggregate results/logs/*/final.json into docs/05_results.md (+ a figure if matplotlib exists)."""
import glob, json, os, collections, statistics as st
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, "results/logs/*/final.json")))]
if not rows:
    raise SystemExit("No results found in results/logs/*/final.json - run experiments first.")

groups = collections.defaultdict(list)
for r in rows:
    groups[(r["task"], r["model"], r.get("rank"), r["seq_len"])].append(r)

lines = ["# 05 Results", "", "_Auto-generated by scripts/make_report.py. Do not edit by hand._", "",
         "| task | model | rank | seq_len | params | n_seeds | val_acc (mean ± std) | val_loss (mean) |",
         "|---|---|---|---|---|---|---|---|"]
for (task, model, rank, L), rs in sorted(groups.items(), key=lambda kv: tuple(str(x) for x in kv[0])):
    acc = [r["val_acc"] for r in rs]
    sd = st.stdev(acc) if len(acc) > 1 else float("nan")
    lines.append(f"| {task} | {model} | {rank} | {L} | {rs[0]['params']:,} | {len(rs)} | "
                 f"{st.mean(acc):.3f} ± {sd:.3f} | {st.mean(r['val_loss'] for r in rs):.3f} |")
open(os.path.join(ROOT, "docs/05_results.md"), "w").write("\n".join(lines) + "\n")
print("wrote docs/05_results.md")

try:
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    tasks = sorted({k[0] for k in groups})
    fig, axes = plt.subplots(1, len(tasks), figsize=(4 * len(tasks), 3.2), squeeze=False)
    for ax, t in zip(axes[0], tasks):
        ks = [(k, v) for k, v in groups.items() if k[0] == t]
        labels = [f"{k[1]}" + (f"\nr={k[2]}" if k[1] == "cgan" else "") for k, _ in ks]
        ax.bar(range(len(ks)), [st.mean(r["val_acc"] for r in v) for _, v in ks])
        ax.set_xticks(range(len(ks))); ax.set_xticklabels(labels, fontsize=7); ax.set_title(t); ax.set_ylim(0, 1)
    fig.tight_layout(); fig.savefig(os.path.join(ROOT, "results/figures/accuracy.png"), dpi=150)
    print("wrote results/figures/accuracy.png")
except ImportError:
    print("matplotlib not installed; skipping figure")
